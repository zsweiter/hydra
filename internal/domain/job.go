package domain

import "time"

type JobStatus uint8

const (
	StatusPending    JobStatus = iota
	StatusProcessing
	StatusCompleted
	StatusFailed
	StatusDeadLetter
)

func (s JobStatus) String() string {
	switch s {
	case StatusPending:
		return "pending"
	case StatusProcessing:
		return "processing"
	case StatusCompleted:
		return "completed"
	case StatusFailed:
		return "failed"
	case StatusDeadLetter:
		return "dead_letter"
	default:
		return "unknown"
	}
}

// Job represents a single executable unit of work.
type Job struct {
	ID          string
	Name        string
	Queue       QueueName
	Data        []byte
	Metadata    map[string]string
	RunAt       time.Time
	Priority    int
	Status      JobStatus
	Attempts    int
	MaxAttempts int
	Backoff     BackoffPolicy

	// ScheduleID references the parent schedule
	// when the job was generated by a JobSchedule.
	ScheduleID     *string
	IdempotencyKey string
	CreatedAt      time.Time
	UpdatedAt      time.Time
}

func NewJob(id, name string, data []byte, metadata map[string]string) Job {
	return Job{
		ID:          id,
		Name:        name,
		Data:        data,
		Metadata:    metadata,
		RunAt:       time.Now().UTC(),
		Status:      StatusPending,
		Attempts:    0,
		MaxAttempts: 3,
		Backoff:     DefaultBackoff(),
		CreatedAt:   time.Now().UTC(),
		UpdatedAt:   time.Now().UTC(),
	}
}

func (j *Job) AddDelay(delay time.Duration) {
	j.RunAt = time.Now().Add(delay)
}

func (j *Job) UpdateStatus(status JobStatus) {
	j.Status = status
	j.UpdatedAt = time.Now().UTC()
}

func (j *Job) IncrementAttempts() {
	j.Attempts++
	j.UpdatedAt = time.Now().UTC()
}

// IsRetryable reports whether the job
// can be retried.
func (j *Job) IsRetryable() bool {
	return j.Attempts < j.MaxAttempts
}

// IsScheduled reports whether the job
// originated from a JobSchedule.
func (j *Job) IsScheduled() bool {
	return j.ScheduleID != nil
}

type BackoffPolicy struct {
	Type   BackoffType
	BaseMs int64
	MaxMs  int64
}

func (b BackoffPolicy) NextDelay(attempt int) time.Duration {
	switch b.Type {
	case BackoffFixed:
		return time.Duration(b.BaseMs) * time.Millisecond
	case BackoffExponential:
		delay := min(
			b.BaseMs*(1<<(attempt-1)), b.MaxMs)
		return time.Duration(delay) * time.Millisecond
	default:
		return 0
	}
}

func DefaultBackoff() BackoffPolicy {
	return BackoffPolicy{
		Type:   BackoffExponential,
		BaseMs: 100,
		MaxMs:  10_000,
	}
}

type BackoffType uint8

const (
	BackoffFixed BackoffType = iota
	BackoffExponential
)
